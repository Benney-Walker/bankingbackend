package com.bynexlabs.bankingbackend.DTO.transaction;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.math.BigDecimal;

/**
 * Request shape for single-account money movements (deposit, share payment, withdrawal), for the
 * desktop and mobile apps. Not yet served by an endpoint: deposits and withdrawals go live once
 * the ledger exists (decision D30).
 *
 * idempotencyKey: generated by the app once per user action (e.g. a UUID) and re-sent unchanged
 * on every retry of that action, so a retried request can never record the money twice.
 */
@Data
@Builder
@AllArgsConstructor
@NoArgsConstructor
public class TransactionRequest {

    @NotBlank(message = "Idempotency key is required")
    @Size(max = 100, message = "Idempotency key must be at most 100 characters")
    private String idempotencyKey;

    @NotBlank(message = "Account number is required")
    private String accountNumber;

    @NotNull(message = "Amount is required")
    private BigDecimal amount;

    @Size(max = 500, message = "Description must be at most 500 characters")
    private String description;
}
