-- V1 created id_entity.id as a plain INT key, but IdEntity maps it as a database-generated
-- identity, so the first insert from IdGenerator failed with a null id.
ALTER TABLE id_entity
ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

-- Rows may already have been inserted by hand; start the identity after the highest existing id.
SELECT setval(
               pg_get_serial_sequence('id_entity', 'id'),
               COALESCE((SELECT MAX(id) FROM id_entity), 0) + 1,
               false
       );